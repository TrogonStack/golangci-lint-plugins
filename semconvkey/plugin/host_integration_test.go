func TestGolangciHost(t *testing.T) {
	binary := os.Getenv("SEMCONVKEY_GOLANGCI_BINARY")
	if binary == "" {
		t.Fatal("set SEMCONVKEY_GOLANGCI_BINARY to a golangci-lint binary built with this plugin")
	}
	binary, err := exec.LookPath(binary)
	if err != nil {
		t.Fatal(err)
	}
	project := t.TempDir()
	writeHostFile(t, project, "go.mod", `module example.com/semconvhost

go 1.27.1

require (
	go.opentelemetry.io/otel v1.47.0
	go.opentelemetry.io/otel/metric v1.47.0
	go.opentelemetry.io/otel/sdk/metric v1.47.0
)
`)
	writeHostFile(t, project, "appsemconv/semconv.go", `// Code generated by host-fixture. DO NOT EDIT.
package appsemconv

import (
	"go.opentelemetry.io/otel/attribute"
	"go.opentelemetry.io/otel/metric"
)

const CounterName = "app.requests"
const TierKey attribute.Key = "app.tier"

func NewCounter(meter metric.Meter) (metric.Int64Counter, error) {
	return meter.Int64Counter(CounterName)
}

func Tier(value string) attribute.KeyValue { return TierKey.String(value) }
`)
	bootstrap := `package probe

import (
	"context"
	"example.com/semconvhost/appsemconv"
	"go.opentelemetry.io/otel/metric"
	"go.opentelemetry.io/otel/semconv/v1.37.0"
	sdkmetric "go.opentelemetry.io/otel/sdk/metric"
)

func Bootstrap() error {
	provider := sdkmetric.NewMeterProvider()
	constructor := appsemconv.NewCounter
	counter, err := constructor(provider.Meter("host"))
	if err != nil { return err }
	counter.Add(context.Background(), 1, metric.WithAttributes(semconv.ServiceName("host"), appsemconv.Tier("test")))
	return provider.Shutdown(context.Background())
}
`
	writeHostFile(t, project, "probe/probe.go", bootstrap)
	output, err := runHostCommand(t, project, "go", "mod", "tidy")
	if err != nil {
		t.Fatalf("prepare real OpenTelemetry dependencies: %v\n%s", err, output)
	}
	const instrumentDiagnostic = "instrument must be created by a package listed in allowed-packages"
	const generatedConstructor = `// Code generated by host-fixture. DO NOT EDIT.
package probe
import "go.opentelemetry.io/otel/metric"
func Create(meter metric.Meter) { _, _ = meter.Int64Counter("app.raw") }
`
	tests := []struct {
		name                 string
		source               string
		generatedInstruments bool
		checkGeneratedFiles  bool
		generatedFilter      string
		wantDiagnostic       string
	}{
		{name: "trusted constructors and provider bootstrap", source: bootstrap, generatedInstruments: true, checkGeneratedFiles: true, generatedFilter: "disable"},
		{
			name: "saved metric constructor", generatedInstruments: true, generatedFilter: "disable", wantDiagnostic: instrumentDiagnostic,
			source: `package probe
import "go.opentelemetry.io/otel/metric"
func Create(meter metric.Meter) { constructor := meter.Int64Counter; _, _ = constructor("app.raw") }
`,
		},
		{
			name: "saved attribute constructor", generatedInstruments: true, generatedFilter: "disable", wantDiagnostic: "takes the key as a raw string",
			source: `package probe
import "go.opentelemetry.io/otel/attribute"
func Create() { constructor := attribute.String; _ = constructor("app.raw", "value") }
`,
		},
		{
			name: "local interface", generatedInstruments: true, generatedFilter: "disable", wantDiagnostic: instrumentDiagnostic,
			source: `package probe
import "go.opentelemetry.io/otel/metric"
type Factory interface { Int64Counter(string, ...metric.Int64CounterOption) (metric.Int64Counter, error) }
func Create(meter Factory) { _, _ = meter.Int64Counter("app.raw") }
`,
		},
		{
			name: "unrelated interface", generatedInstruments: true, generatedFilter: "disable",
			source: `package probe
type Factory interface { Int64Counter(string) (int, error) }
func Create(factory Factory) { _, _ = factory.Int64Counter("unrelated") }
`,
		},
		{
			name: "SDK string is not a semantic key", generatedInstruments: true, generatedFilter: "disable", wantDiagnostic: "attribute key must come from",
			source: `package probe
import (
	"go.opentelemetry.io/otel"
	"go.opentelemetry.io/otel/attribute"
)
func Create() { _ = attribute.Key(otel.Version()).String("value") }
`,
		},
		{
			name: "name-only default remains valid", generatedFilter: "disable",
			source: `package probe
import (
	"example.com/semconvhost/appsemconv"
	"go.opentelemetry.io/otel/metric"
)
func Create(meter metric.Meter) { _, _ = meter.Int64Counter(appsemconv.CounterName) }
`,
		},
		{name: "generated check remains opt in", source: generatedConstructor, generatedInstruments: true, generatedFilter: "disable"},
		{name: "host generated exclusion filters issues", source: generatedConstructor, generatedInstruments: true, checkGeneratedFiles: true, generatedFilter: "strict"},
		{name: "generated check visible through host", source: generatedConstructor, generatedInstruments: true, checkGeneratedFiles: true, generatedFilter: "disable", wantDiagnostic: instrumentDiagnostic},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			writeHostFile(t, project, "probe/probe.go", test.source)
			configuration := fmt.Sprintf(`version: "2"
linters:
  default: none
  enable: [semconvkey]
  exclusions:
    generated: %s
  settings:
    custom:
      semconvkey:
        type: module
        settings:
          allowed-packages: [example.com/semconvhost/appsemconv]
          generated-instruments: %t
`, test.generatedFilter, test.generatedInstruments)
			if test.checkGeneratedFiles {
				configuration += "          check-generated-files: true\n"
			}
			writeHostFile(t, project, ".golangci.yml", configuration)
			output, err := runHostCommand(t, project, binary, "run", "--config", ".golangci.yml", "./probe")
			if test.wantDiagnostic == "" {
				if err != nil {
					t.Fatalf("unexpected host failure: %v\n%s", err, output)
				}
				return
			}
			var failure *exec.ExitError
			if !errors.As(err, &failure) || failure.ExitCode() != 1 || !strings.Contains(output, test.wantDiagnostic) {
				t.Fatalf("want diagnostic %q and exit 1, got %v\n%s", test.wantDiagnostic, err, output)
			}
		})
	}
}

func writeHostFile(t *testing.T, project, name, contents string) {
	t.Helper()
	filename := filepath.Join(project, name)
	if err := os.MkdirAll(filepath.Dir(filename), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filename, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
}

func runHostCommand(t *testing.T, project, binary string, arguments ...string) (string, error) {
	t.Helper()
	commandContext, cancel := context.WithTimeout(t.Context(), 2*time.Minute)
	defer cancel()
	command := exec.CommandContext(commandContext, binary, arguments...)
	command.Dir = project
	output, err := command.CombinedOutput()
	return string(output), err
}
